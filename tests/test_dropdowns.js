const assert=require('assert'),fs=require('fs'),path=require('path'),vm=require('vm');
const root=path.resolve(__dirname,'..');const index=process.argv.indexOf('--studiox-root');
const host=index<0?path.resolve(root,'../blockly'):process.argv[index+1];
const Blockly=require(path.join(host,'node_modules/blockly'));require(path.join(host,'node_modules/blockly/blocks'));
vm.runInNewContext(fs.readFileSync(path.join(root,'frontend/libraryBlocks.js'),'utf8'),{Blockly,StudioXArduinoCppTypes:require('../frontend/cppTypes')});
const {compile}=require('../frontend/compiler');
const ctor={id:'ctor',owner:'Servo',qualifiedName:'Servo',name:'Servo',constructor:true,parameters:[],returnKind:'void',header:'Servo.h',library:'Servo',supported:true};
const write={...ctor,id:'write',constructor:false,name:'write',qualifiedName:'Servo::write',parameters:[{name:'angle',type:'int',kind:'number'}],returnType:'void'};
const overload={...write,id:'overload',parameters:[...write.parameters,{name:'speed',type:'int',kind:'number'}]};
const read={...write,id:'read',name:'read',qualifiedName:'Servo::read',parameters:[],returnKind:'number',returnType:'int'};
const options=[ctor,write,overload,read];
const model={id:'servo',name:'servo',type:''};
const value={type:'arduino_library_value',extraState:{signature:ctor,options}};
(async()=>{
 const workspace=new Blockly.Workspace();
 const setter=Blockly.serialization.blocks.append({type:'variables_set',fields:{VAR:model},inputs:{VALUE:{block:value}}},workspace);
 const constructor=setter.getInputTargetBlock('VALUE');
 assert.ok(constructor.outputConnection&&!constructor.previousConnection);
 assert.strictEqual(constructor.getField('VAR'),null,'constructor uses the surrounding set variable');
 const call=Blockly.serialization.blocks.append({type:'arduino_library_value',extraState:{signature:write,options},fields:{VAR:model}},workspace);
 assert.ok(call.previousConnection&&!call.outputConnection,'void calls become statements');
 assert.strictEqual(call.getField('FUNC_NAME').getOptions(false).length,4,'one dropdown holds all overloads');
 call.getInputTargetBlock('ARG_0').setFieldValue(90,'NUM');
 const angle=call.getInputTargetBlock('ARG_0');
 call.setFieldValue('overload','FUNC_NAME');
 assert.strictEqual(call.getInputTargetBlock('ARG_0'),angle,'matching arguments survive an overload change');
 assert.ok(call.getInput('ARG_1'));
 await new Promise(resolve=>setTimeout(resolve,15));workspace.clearUndo();
 call.setFieldValue('read','FUNC_NAME');
 assert.strictEqual(call.getInput('ARG_0'),null);assert.ok(call.outputConnection&&!call.previousConnection);
 await new Promise(resolve=>setTimeout(resolve,15));
 workspace.undo(false);
 assert.strictEqual(call.saveExtraState().signature.id,'overload','undo restores the signature and shape');
 assert.ok(call.getInput('ARG_1'));assert.strictEqual(call.getInputTargetBlock('ARG_0').getFieldValue('NUM'),90);
 workspace.undo(true);
 assert.strictEqual(call.saveExtraState().signature.id,'read');assert.ok(call.outputConnection);
 // Put read into a standard value consumer, keeping the constructor assignment.
 const output=workspace.newBlock('text_print');output.getInput('TEXT').connection.connect(call.outputConnection);
 workspace.getVariableMap().renameVariable(workspace.getVariableMap().getVariableById('servo'),'arm');
 let state=Blockly.serialization.workspaces.save(workspace),generated=compile(state);
 assert.deepStrictEqual(generated.diagnostics,[]);
 assert.match(generated.code,/Servo v_arm;/);
 assert.ok(!generated.code.includes('StudioXObject'));
 assert.ok(!generated.code.includes('v_arm ='));
 assert.match(generated.code,/v_arm.read\(\)/);
 const optionalSpec={...write,id:'optional',parameters:[...write.parameters,{name:'speed',type:'int',kind:'number',optional:true,default:'10'}]};
 const optionalCall=Blockly.serialization.blocks.append({type:'arduino_library_value',extraState:{signature:optionalSpec}},workspace);
 optionalCall.setFieldValue('TRUE','OPTIONAL');optionalCall.getInputTargetBlock('ARG_1').setFieldValue(88,'NUM');
 await new Promise(resolve=>setTimeout(resolve,15));workspace.clearUndo();
 optionalCall.setFieldValue('FALSE','OPTIONAL');
 await new Promise(resolve=>setTimeout(resolve,15));workspace.undo(false);
 assert.strictEqual(optionalCall.getInputTargetBlock('ARG_1').getFieldValue('NUM'),88,'undo restores an optional argument value');
 optionalCall.dispose();
 const copy=new Blockly.Workspace();Blockly.serialization.workspaces.load(state,copy);
 assert.strictEqual(copy.getBlocksByType('arduino_library_value')[0].saveExtraState().options.length,4);
 assert.deepStrictEqual(compile(Blockly.serialization.workspaces.save(copy)).diagnostics,[]);
 const xml=Blockly.Xml.workspaceToDom(workspace);const xmlCopy=new Blockly.Workspace();Blockly.Xml.domToWorkspace(xml,xmlCopy);
 assert.deepStrictEqual(compile(Blockly.serialization.workspaces.save(xmlCopy)).diagnostics,[]);
 const constants=[{id:'LOW',name:'LOW',qualifiedName:'LOW',header:'Arduino.h',library:'Core',kind:'number'},
  {id:'READY',name:'READY',qualifiedName:'READY',header:'Arduino.h',library:'Core',kind:'boolean'}];
 const constant=Blockly.serialization.blocks.append({type:'arduino_library_constant',extraState:{signature:constants[0],options:constants}},workspace);
 constant.setFieldValue('READY','CONST_NAME');
 assert.strictEqual(constant.saveExtraState().signature.name,'READY');
 assert.strictEqual(constant.outputConnection.getCheck()[0],'Boolean');
 const roundtrip=new Blockly.Workspace();Blockly.Xml.domToBlock(Blockly.Xml.blockToDom(constant),roundtrip);
 assert.strictEqual(roundtrip.getTopBlocks()[0].getFieldValue('CONST_NAME'),'READY');
 assert.strictEqual(roundtrip.getTopBlocks()[0].saveExtraState().options.length,2);
 for(const ws of [workspace,copy,xmlCopy,roundtrip])ws.dispose();
 console.log('Dropdowns passed: overload parameters/defaults, preserved inputs, undo/redo, constructor values, ordinary variables, rename linking, constants, JSON and XML.');
})().catch(error=>{console.error(error);process.exitCode=1});
